// Keeps the Windows CMake path fix alive across `expo prebuild`.
//
// `android/` is generated and gitignored, so every prebuild rewrites
// settings.gradle from Expo's template and throws away anything hand-added to
// it. This config plugin re-appends the fix each time.
//
// Why the fix is needed at all:
//   CMake on Windows refuses object paths longer than 250 characters. pnpm's
//   store nests expo-modules-core at
//     node_modules/.pnpm/expo-modules-core@57.0.18_r_<hash>/node_modules/expo-modules-core/
//   and that path is counted TWICE -- once as the module's `.cxx` directory,
//   and again encoded into each object filename, because the sources live
//   outside the build directory. Over the limit, the native build dies with:
//     ninja: error: manifest 'build.ninja' still dirty after 100 tries
//   Pointing `externalNativeBuild.cmake.buildStagingDirectory` at a short path
//   (e.g. D:/cx/<module>) brings both copies back under the limit.
//
// Two traps already paid for, preserved in the generated Groovy below:
//   1. The hook must attach via `plugins.withId` from `gradle.beforeProject`,
//      NOT `subprojects { afterEvaluate { } }`. By then the Expo plugins have
//      already evaluated some projects, and Gradle throws "Cannot run
//      Project.afterEvaluate(Closure) when the project is already evaluated".
//   2. The staging path must be SHORT. The object filename encodes the full
//      source path, so a long staging root defeats the whole exercise -- don't
//      "tidy" it into something like <project>/build/cxx.
//
// Options (all optional), via app.json:
//   ["./plugins/withShortNativeBuildPath", { "stagingRoot": "E:/cx" }]
// With no option the generated Groovy derives the root at build time as
// <drive of the android project>/cx, so it is correct wherever the repo is
// checked out and whoever ran the prebuild. The CAIRN_NATIVE_BUILD_DIR
// environment variable overrides it for a single build.
// On non-Windows the generated block does nothing: the path limit is a Windows
// quirk, and redirecting the staging directory elsewhere would only be noise.

// pnpm's strict node_modules layout does not expose @expo/config-plugins to
// this package, so reach it the way Expo resolves its own dependencies.
function requireConfigPlugins() {
  try {
    return require('@expo/config-plugins');
  } catch (e) {
    return require(
      require.resolve('@expo/config-plugins', {
        paths: [require.resolve('expo/package.json', { paths: [__dirname] })],
      })
    );
  }
}

const { withSettingsGradle } = requireConfigPlugins();

const MARKER_BEGIN =
  '// >>> cairn:short-native-build-path (generated by plugins/withShortNativeBuildPath.js)';
const MARKER_END = '// <<< cairn:short-native-build-path';

function groovyString(value) {
  return "'" + String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
}

function renderBlock(stagingRoot) {
  // With no explicit root, derive it from the drive the android project sits on
  // (inside a settings script, rootDir is the android/ directory itself).
  const defaultRootExpr = stagingRoot
    ? groovyString(String(stagingRoot).replace(/\\/g, '/'))
    : "new File(rootDir.toPath().getRoot().toFile(), 'cx').path";

  return `
${MARKER_BEGIN}
// Windows only: CMake refuses object paths over 250 characters, and pnpm's store
// nests expo-modules-core deep enough that its .cxx directory alone eats most of
// them -- the source path is counted twice, once as the .cxx directory and again
// encoded into every object filename. Without this the native build dies with
// "ninja: error: manifest 'build.ninja' still dirty after 100 tries".
//
// Do NOT rewrite this as subprojects { afterEvaluate { } }: by this point the
// Expo plugins have already evaluated some projects, and Gradle throws "Cannot
// run Project.afterEvaluate(Closure) when the project is already evaluated".
// Hooking each module as its Android plugin applies is what works.
//
// Do NOT lengthen the staging path either (no <project>/build/cxx): the object
// filename encodes the full source path, so only a short root stays under 250.
//
// Generated by apps/mobile/plugins/withShortNativeBuildPath.js -- edit the
// plugin, not this file, which the next \`expo prebuild\` will overwrite.
def cairnIsWindows = System.getProperty('os.name').toLowerCase().contains('windows')
def cairnNativeBuildRoot = System.getenv('CAIRN_NATIVE_BUILD_DIR')
if (!cairnNativeBuildRoot && cairnIsWindows) {
  cairnNativeBuildRoot = ${defaultRootExpr}
}
if (cairnNativeBuildRoot) {
  gradle.beforeProject { project ->
    ['com.android.application', 'com.android.library'].each { pluginId ->
      project.plugins.withId(pluginId) {
        project.extensions.getByName('android')
          .externalNativeBuild.cmake.buildStagingDirectory =
            new File(cairnNativeBuildRoot, project.name)
      }
    }
  }
}
${MARKER_END}
`;
}

function appendBlock(contents, stagingRoot) {
  // Strip any block we generated before, so repeated prebuilds (or a changed
  // option) leave exactly one up-to-date copy rather than a growing stack.
  const begin = contents.indexOf(MARKER_BEGIN);
  if (begin !== -1) {
    const end = contents.indexOf(MARKER_END, begin);
    contents =
      end === -1
        ? contents.slice(0, begin)
        : contents.slice(0, begin) + contents.slice(end + MARKER_END.length);
  }
  return contents.replace(/\s+$/, '') + '\n' + renderBlock(stagingRoot);
}

const withShortNativeBuildPath = (config, options = {}) => {
  return withSettingsGradle(config, (cfg) => {
    if (cfg.modResults.language !== 'groovy') {
      // Only the Groovy settings script is handled; a .kts project would need
      // the same hook rewritten in Kotlin.
      throw new Error(
        'withShortNativeBuildPath: expected a Groovy settings.gradle, got ' +
          cfg.modResults.language
      );
    }
    cfg.modResults.contents = appendBlock(
      cfg.modResults.contents,
      options.stagingRoot
    );
    return cfg;
  });
};

module.exports = withShortNativeBuildPath;
// Exported so the string surgery can be exercised without running a prebuild.
module.exports.appendBlock = appendBlock;
module.exports.MARKER_BEGIN = MARKER_BEGIN;
module.exports.MARKER_END = MARKER_END;
